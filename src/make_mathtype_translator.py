# -*- coding: utf-8 -*-
"""Нарисовать транслятор MathType с поддержкой кириллицы: "LaTeX Cyrillic.tdl".

Запуск: C:\\Tools\\Scripts\\Python314\\python.exe src/make_mathtype_translator.py [путь-для-файла]
По умолчанию файл кладётся в res\\ (рядом с иконкой, как у make_icon.py); его нужно
скопировать в папку Translators установки MathType
(C:\\Program Files (x86)\\MathType\\Translators\\) — нужны права администратора.
После этого в Word: MathType -> Convert Equations -> "Text using the MathType translator:
LaTeX (Cyrillic)" — формулы с русскими индексами (Р_накр и т.п.) перестанут
теряться при пакетной конвертации: без этих правил транслятор падает на
первой кириллической букве и молча выбрасывает всю формулу.

Правила покрывают весь блок Ѐ..џ (U+0400–U+045F: русские, украинские, сербские,
македонские, белорусские, болгарские буквы) и Ґ/ґ (U+0490–U+0491).

Зачем \\text{...}: кириллица в math-режиме LaTeX сама по себе не набирается,
а обёртка в \\text делает формулу компилируемой и искомой.
"""
import sys
from pathlib import Path

BS = chr(92)  # бэкслеш без литералов, чтобы не зависеть от экранирования
ENCODING = "cp1251"  # системная ANSI-кодировка русской Windows, как у родных .tdl


def tex_char(code: int) -> str:
    """\\text{...} для символа.

    Четырёх букв — Ѐ (U+0400), Ѝ (U+040D), ѐ (U+0450), ѝ (U+045D) — нет в cp1251,
    в файл их не записать; выводим LaTeX-акцентом над обычной буквой (\\`{е} = ѐ),
    он проходит и xelatex, и texmath.
    """
    accented = {0x0400: "Е", 0x040D: "И", 0x0450: "е", 0x045D: "и"}
    if code in accented:
        return BS + "text{" + BS + "`{" + accented[code] + "}}"
    return BS + "text{" + chr(code) + "}"


def rule_comment(code: int) -> str:
    """Комментарий правила; для не-кодируемых букв — без самого символа."""
    if code in (0x0400, 0x040D, 0x0450, 0x045D):
        return "U+%04X (нет в cp1251, акцентом)" % code
    return chr(code)


def translator_text() -> str:
    lines = [
        'MathType Output Translator 1.0: "LaTeX (Cyrillic)", '
        '"LaTeX translator with Cyrillic letters (generated by PDFConv)", language',
        "",
        "// Based on LaTeX.tdl (c) Design Science; the TDL license permits derivative",
        "// translators for use with MathType. Adds Cyrillic char rules so equations",
        "// with Cyrillic subscripts (e.g. P_nakr) translate instead of being dropped.",
        "",
        'include "LaTeX (base vars).tdl";',
        'var/"TranslatorName" = "LaTeX (Cyrillic)";',
        'var/"TranslatorFileName" = "LaTeX Cyrillic.tdl";',
        "",
        'include "LaTeX (base rules).tdl";',
        "",
        "// ---- Cyrillic ----",
    ]
    codes = list(range(0x0400, 0x0460)) + [0x0490, 0x0491]  # Ѐ..џ целиком, плюс Ґ/ґ
    for code in codes:
        lines.append('char/0x%04X       = "%s";    // %s'
                     % (code, tex_char(code), rule_comment(code)))
    return ("\r\n".join(lines) + "\r\n").encode(ENCODING)


def main() -> int:
    default = Path(__file__).resolve().parent.parent / "res" / "LaTeX Cyrillic.tdl"
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else default
    target.write_bytes(translator_text())
    print("Записан: %s" % target)
    print("Скопируйте его в папку Translators установки MathType и перезапустите Word:")
    print("  C:\\Program Files (x86)\\MathType\\Translators\\")
    print("Затем: Convert Equations -> Text using the MathType translator: LaTeX (Cyrillic).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
